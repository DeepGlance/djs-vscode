// Ported from dmd/deps.d (module dmd.deps).
//
// The `-deps` and `-makedeps` switches, which output dependencies of modules for build tools.
//
// The grammar of the `-deps` output is:
//
//     ImportDeclaration
//         ::= BasicImportDeclaration [ " : " ImportBindList ] [ " -> " ModuleAliasIdentifier ] "\n"
//
//     BasicImportDeclaration
//         ::= ModuleFullyQualifiedName " (" FilePath ") : " Protection|"string"
//             " [ " static" ] : " ModuleFullyQualifiedName " (" FilePath ")"
//
//     FilePath
//         - any string with '(', ')' and '\' escaped with the '\' character
//
// Make dependencies as generated by `-makedeps` look like `source/app.d:` followed by one
// ` \`-continued `  source/importa.d` line per dependency.
//
// Translation notes:
//   * `const(char)*` C-strings are `DString`s whose logical end is the first NUL (02 §11.2), so the
//     `*fname` walk of `writeEscapedMakePath` and `.ptr` hand-offs (`fileNameZ.ptr`) are the slice
//     itself.
//   * `pure` erases (04 §8). `version (Windows)` is OFF (_config.md): the `:` arm escapes.
//   * `version (IN_LLVM)` is ON: the `!IN_LLVM` arms of `writeMakeDeps` are dead and dropped. The two
//     bodiless `extern(C++)` declarations (deps.d:53/:55) are implemented by LDC's driver, whose
//     state (`gExePath`, `gStaticLibPath`, set by a completed link or archive step) does not exist in
//     this port: see the escalation stubs in `writeMakeDeps`.
//   * The `unittest` (deps.d:242) is ported in deps.test.ts.
//
// Load order (01 §4.8): `hdrgen.js` and `utils.js` are value imports reaching the core SCC, so they
// come last; `Import`/`Module`/`Param`/`Output` are `import type`.

import { cstr, ds, dsEquals, type DString } from "../dstring.js";
import { assertUnreachable } from "../assert.js";
import { OutBuffer } from "./common/outbuffer.js";
import { Id } from "./id.js";

import type { Import } from "./dimport.js";
import type { Module } from "./dmodule.js";
import type { Param, Output } from "./globals.js";

import { visibilityToBuffer } from "./hdrgen.js";
import { escapePath } from "./utils.js";

/**
 * dmd/deps.d:68 — `void writeMakeDeps(ref OutBuffer buf, const ref Param params, bool link, bool lib,`.
 * Output the makefile dependencies for the `-makedeps` switch.
 *
 * Params:
 *   buf = outbuffer to write into
 *   params = dmd params
 *   link = an executable is being generated
 *   lib = a library is being generated
 *   libExt = file extension of libraries for current target (read only by the `!IN_LLVM` arm, dead here)
 *
 * The first target line depends on which output the driver produced. Under IN_LLVM the executable
 * and library paths come from the driver (`getPathToProducedBinary` / `getPathToProducedStaticLibrary`),
 * which this port cannot answer (escalation stubs below); the object-file arms are complete.
 */
export function writeMakeDeps(buf: OutBuffer, params: Param, link: boolean, lib: boolean, _libExt: DString): void {
    // start by resolving and writing the target (which is sometimes resolved during link phase)
    if (link) { // deps.d:70 — `link && (IN_LLVM || params.exefile)`; IN_LLVM is ON
        // DJS-ESCALATE: getPathToProducedBinary is LDC driver state (driver/linker.cpp:303, gExePath)  (dmd/deps.d:55)
        throw new Error("DJS-ESCALATE: getPathToProducedBinary (dmd/deps.d:55) at dmd/deps.d:75");
    }
    else if (lib) {
        // DJS-ESCALATE: getPathToProducedStaticLibrary is LDC driver state (driver/archiver.cpp:356)  (dmd/deps.d:53)
        throw new Error("DJS-ESCALATE: getPathToProducedStaticLibrary (dmd/deps.d:53) at dmd/deps.d:85");
    }
    else if (params.objname !== null) { // deps.d:98 — `else if (params.objname)`: slice pointer test (06 §2.8)
        writeEscapedMakePath(buf, params.objname);
    }
    else if (params.objfiles.length) {
        writeEscapedMakePath(buf, params.objfiles.opIndex(0));
        for (let i = 1; i < params.objfiles.length; i++) { // deps.d:104 — `params.objfiles[1 .. $]`
            buf.writestring(ds(" "));
            writeEscapedMakePath(buf, params.objfiles.opIndex(i));
        }
    }
    else {
        assertUnreachable("cannot resolve makedeps target");
    }

    buf.writestring(ds(":"));

    // then output every dependency
    for (let i = 0; i < params.makeDeps.files.length; i++) {
        buf.writestringln(ds(" \\"));
        buf.writestring(ds("  "));
        writeEscapedMakePath(buf, params.makeDeps.files.opIndex(i));
    }
    buf.writenl();
}

/**
 * dmd/deps.d:135 — `void addImportExpDep(ref Output moduleDeps, ref Output makeDeps, const(char)[] fileNameZ,`.
 * Add an import expression to module dependencies.
 *
 * Params:
 *   moduleDeps = output settings for `-deps`
 *   makeDeps = output settings for `-makedeps`
 *   fileNameZ = 0-terminated string containing the import expression's resolved filename
 *   importString = raw string passed to import exp
 *   imod = module import exp is in
 *
 * Both sinks are optional: nothing is written unless `moduleDeps.buffer` is set (`-deps`) or
 * `makeDeps.doOutput` is set (`-makedeps`, appends to `makeDeps.files`).
 */
export function addImportExpDep(moduleDeps: Output, makeDeps: Output, fileNameZ: DString, importString: DString,
    imod: Module): void {
    if (moduleDeps.buffer !== null) {
        const ob: OutBuffer = moduleDeps.buffer;

        if (moduleDeps.name === null) // deps.d:141 — `if (!moduleDeps.name)`: slice pointer test (06 §2.8)
            ob.writestring(ds("depsFile "));
        ob.writestring(imod.toPrettyChars());
        ob.writestring(ds(" ("));
        escapePath(ob, imod.srcfile.toChars());
        ob.writestring(ds(") : "));
        if (moduleDeps.name !== null)
            ob.writestring(ds("string : "));
        ob.write(importString);
        ob.writestring(ds(" ("));
        escapePath(ob, fileNameZ);
        ob.writestring(ds(")"));
        ob.writenl();
    }
    if (makeDeps.doOutput) {
        makeDeps.files.push(fileNameZ);
    }
}

/**
 * dmd/deps.d:168 — `void addImportDep(ref Output moduleDeps, Import imp, Module imod)`. Add an
 * import statement to module dependencies.
 *
 * Params:
 *   moduleDeps = output settings
 *   imp = import to add
 *   imod = module that the import is in
 *
 * Writes nothing when `moduleDeps.buffer` is null, for the `object` self-import, and for the
 * pseudo module `__main`.
 */
export function addImportDep(moduleDeps: Output, imp: Import, imod: Module): void {
    // object self-imports itself, so skip that
    // https://issues.dlang.org/show_bug.cgi?id=7547
    // don't list pseudo modules __entrypoint.d, __main.d
    // https://issues.dlang.org/show_bug.cgi?id=11117
    // https://issues.dlang.org/show_bug.cgi?id=11164
    if (moduleDeps.buffer === null || (imp.id === Id.object && imod.ident === Id.object) ||
        dsEquals(cstr(imod.ident!.toChars()), ds("__main")))
        return;

    const ob: OutBuffer = moduleDeps.buffer;
    if (moduleDeps.name === null)
        ob.writestring(ds("depsImport "));
    ob.writestring(imod.toPrettyChars());
    ob.writestring(ds(" ("));
    escapePath(ob, imod.srcfile.toChars());
    ob.writestring(ds(") : "));
    // use visibility instead of sc.visibility because it couldn't be
    // resolved yet, see the comment above
    visibilityToBuffer(ob, imp.visibility);
    ob.writeByte(0x20); // ' '
    if (imp.isstatic !== 0) {
        ob.writestring(ds("static "));
    }
    ob.writestring(ds(": "));
    // deps.d:195 — `foreach (pid; imp.packages)`: a null slice iterates zero times (06 §2.8)
    for (const pid of imp.packages ?? []) {
        ob.printf(ds("%s."), pid.toChars());
    }
    ob.writestring(imp.id!.toString());
    ob.writestring(ds(" ("));
    if (imp.mod !== null)
        escapePath(ob, imp.mod.srcfile.toChars());
    else
        ob.writestring(ds("???"));
    ob.writeByte(0x29); // ')'
    for (let i = 0; i < imp.names.length; i++) {
        const name = imp.names.opIndex(i)!;
        if (i === 0)
            ob.writeByte(0x3a); // ':'
        else
            ob.writeByte(0x2c); // ','
        const _alias = imp.aliases.opIndex(i);
        if (_alias === null) {
            ob.printf(ds("%s"), name.toChars()); // deps.d:210 `_alias = name` is a dead store, dropped
        }
        else
            ob.printf(ds("%s=%s"), _alias.toChars(), name.toChars());
    }
    if (imp.aliasId !== null)
        ob.printf(ds(" -> %s"), imp.aliasId.toChars());
    ob.writenl();
}

/**
 * dmd/deps.d:238 — `void writeEscapedMakePath(ref OutBuffer buf, const(char)* fname) pure`. Takes a
 * path, and makes it compatible with GNU Makefile format.
 *
 * GNU make uses a weird quoting scheme for white space.
 * A space or tab preceded by 2N+1 backslashes represents N backslashes followed by space;
 * a space or tab preceded by 2N backslashes represents N backslashes at the end of a file name;
 * and backslashes in other contexts should not be doubled.
 *
 * Params:
 *   buf = Buffer to write the escaped path to
 *   fname = Path to escape (a C-string: the walk stops at the first NUL)
 */
export function writeEscapedMakePath(buf: OutBuffer, fname: DString): void {
    let slashes = 0; // `uint slashes`; only ever incremented from 0 and reset to 0

    for (let i = 0; i < fname.length && fname[i] !== 0; i++) { // `while (*fname)`
        const c = fname[i];
        switch (c) {
            case 0x5c: // '\\'
                slashes++;
                break;
            case 0x24: // '$'
                buf.writeByte(0x24);
                slashes = 0; // goto default
                break;
            case 0x20: // ' '
            case 0x09: // '\t'
                // `while (slashes--)`: one iteration per pending backslash; the post-decrement wraps the
                // `uint` after the last test, but the `goto default` below resets it to 0 anyway.
                while (slashes-- > 0)
                    buf.writeByte(0x5c);
                buf.writeByte(0x5c); // goto case '#'
                slashes = 0; // goto default
                break;
            case 0x23: // '#'
                buf.writeByte(0x5c);
                slashes = 0; // goto default
                break;
            case 0x3a: // ':'
                // ':' not escaped on Windows because it can create problems with absolute paths; ON
                // for our target (`version (Windows) {} else`).
                buf.writeByte(0x5c);
                slashes = 0; // goto default
                break;
            default:
                slashes = 0;
                break;
        }

        buf.writeByte(c);
    }
}
