// Tests for src/dmd/dscope.ts (port of dmd/dscope.d).
//
// dscope.d carries ZERO `unittest` blocks, so this file takes the 10 §1.6b shape: one module-load
// smoke test plus a small set of behavior pins for things that ARE constructible with no harness
// (a bare `new Scope()` needs no init snippet). Every expected value below is read off the D
// source, never off the TS: the field initializers at dmd/dscope.d:178/181/185/192, the bit layout
// that dmd/common/bitfields.d generates for the three `generateBitFields` mixins
// (dmd/dscope.d:118/199/201), and the bodies of push/pop/copyFlagsFrom/resetAllFlags/startCTFE.

import { describe, test, expect } from "vitest";

import { Scope, Contract, Previews, FlagBitFields, NonFlagBitFields } from "./dscope.js";
import { LINK, CPPMANGLE, Edition } from "./astenums.js";
import { FeatureState } from "./globals.js";
import { Visibility, ScopeDsymbol } from "./dsymbol.js";

describe("dscope module load", () => {
    test("smoke: the module loads and `Scope` is constructible at init values", () => {
        const sc = new Scope();
        // dmd/dscope.d:178/181/185/192 — the only non-zero field initializers in the struct.
        expect(sc.linkage).toBe(LINK.d);
        expect(sc.cppmangle).toBe(CPPMANGLE.def);
        expect(sc.emitInstrumentation).toBe(true); // version (IN_LLVM) -> ON
        expect(sc.visibility.kind).toBe(Visibility.Kind.public_);
        // Everything else is `.init`: null refs, both packed words zero.
        expect(sc.enclosing).toBe(null);
        expect(sc._module).toBe(null);
        expect(sc.bitFields).toBe(0);
        expect(sc.bitFields2).toBe(0);
        expect(sc.contract).toBe(Contract.none);
        expect(sc.intypeof).toBe(0);
    });

    test("the three bitfield SPEC structs carry the D `.init` values", () => {
        // dmd/dscope.d:47/84 and the nested dmd/dscope.d:99 — never instantiated in D; they are the
        // declarative input to generateBitFields, so all that is pinned is their init values (which
        // are what makes the generated initial word 0 in all three mixins).
        const f = new FlagBitFields();
        expect(f.contract).toBe(Contract.none);
        expect(f.ctor).toBe(false);
        expect(f.deferSemantic3InCompilerHook).toBe(false);
        const n = new NonFlagBitFields();
        expect(n.intypeof).toBe(0);
        expect(n.explicitVisibility).toBe(false);
        const p = new Previews.BitFields();
        expect(p.systemVariables).toBe(FeatureState.default_);
        expect(p.dip1000).toBe(false);
    });

    test("the three spec structs satisfy the 03 §2 value-struct copy() contract", () => {
        // 03 §2: every TS class backing a D struct provides copy(); all fields here are
        // primitive/enum, so the copy is field-wise by value and fully independent.
        const f = new FlagBitFields();
        f.contract = Contract.ensure;
        f.deferSemantic3InCompilerHook = true;
        const f2 = f.copy();
        expect(f2.contract).toBe(Contract.ensure);
        expect(f2.deferSemantic3InCompilerHook).toBe(true);
        f2.contract = Contract.none;
        expect(f.contract).toBe(Contract.ensure);

        const n = new NonFlagBitFields();
        n.intypeof = 0xAB;
        n.explicitVisibility = true;
        const n2 = n.copy();
        expect(n2.intypeof).toBe(0xAB);
        expect(n2.explicitVisibility).toBe(true);
        n2.intypeof = 0;
        expect(n.intypeof).toBe(0xAB);

        const p = new Previews.BitFields();
        p.systemVariables = FeatureState.enabled;
        p.safer = true;
        const p2 = p.copy();
        expect(p2.systemVariables).toBe(FeatureState.enabled);
        expect(p2.safer).toBe(true);
        p2.safer = false;
        expect(p.safer).toBe(true);
    });
});

describe("generateBitFields expansion — the packed words", () => {
    // Layout generated by dmd/common/bitfields.d for `generateBitFields!(FlagBitFields, ushort)`
    // (bit size = bsr(memType.max | 1) + 1, offsets in declaration order):
    //   ctor 0 noAccessCheck 1 condition 2 debug_ 3 inTemplateConstraint 4 contract 5(2 bits)
    //   ctfe 7 traitsCompiles 8 ignoresymbolvisibility 9 inCfile 10 canFree 11 fullinst 12
    //   ctfeBlock 13 knownACompileTimeOnlyContext 14 deferSemantic3InCompilerHook 15
    test("FlagBitFields members pack into `bitFields` at the generated offsets", () => {
        const sc = new Scope();
        sc.ctor = true;
        expect(sc.bitFields).toBe(1 << 0);
        sc.ctor = false;
        expect(sc.bitFields).toBe(0);

        sc.deferSemantic3InCompilerHook = true; // the last bit of the ushort
        expect(sc.bitFields).toBe(1 << 15);
        expect(sc.deferSemantic3InCompilerHook).toBe(true);
        expect(sc.knownACompileTimeOnlyContext).toBe(false);
        sc.deferSemantic3InCompilerHook = false;

        // `contract` is a 2-bit field (Contract.max == ensure == 3) at offset 5.
        sc.contract = Contract.ensure;
        expect(sc.bitFields).toBe(3 << 5);
        expect(sc.contract).toBe(Contract.ensure);
        sc.contract = Contract.require;
        expect(sc.bitFields).toBe(2 << 5); // narrowing the value clears the old bits first
        expect(sc.ctfe).toBe(false);       // the adjacent bit (offset 7) is untouched
    });

    test("NonFlagBitFields live in the SECOND word, so resetAllFlags/copyFlagsFrom skip them", () => {
        const sc = new Scope();
        sc.intypeof = 0xAB; // ubyte field, 8 bits at offset 0 of bitFields2
        sc.nofree = true;   // offset 8
        expect(sc.bitFields2).toBe(0xAB | (1 << 8));
        expect(sc.bitFields).toBe(0);

        sc.ctfe = true;
        sc.resetAllFlags(); // dmd/dscope.d:289 — `this.bitFields = 0`
        expect(sc.bitFields).toBe(0);
        expect(sc.ctfe).toBe(false);
        expect(sc.intypeof).toBe(0xAB); // survives: it is not in `bitFields`
        expect(sc.nofree).toBe(true);

        const other = new Scope();
        other.traitsCompiles = true;
        other.inCfile = true;
        other.explicitVisibility = true; // bitFields2 — must NOT travel
        sc.copyFlagsFrom(other);         // dmd/dscope.d:283 — `this.bitFields = other.bitFields`
        expect(sc.traitsCompiles).toBe(true);
        expect(sc.inCfile).toBe(true);
        expect(sc.explicitVisibility).toBe(false);
        expect(sc.intypeof).toBe(0xAB);
    });

    test("Previews packs into its own word and copies by value (03 §2)", () => {
        const p = new Previews();
        p.dip1000 = true;                                // offset 1
        p.systemVariables = FeatureState.enabled;        // offset 13, 2 bits
        expect(p.bitFields).toBe((1 << 1) | (2 << 13));
        const q = p.copy();
        expect(q.bitFields).toBe(p.bitFields);
        q.dip1000 = false;
        expect(p.dip1000).toBe(true); // the copy is independent
    });
});

describe("Scope.push / pop / startCTFE", () => {
    test("push() links the child, resets flags, and keeps exactly the persistent ones", () => {
        const parent = new Scope();
        // persistent across push (dmd/dscope.d:265-277)
        parent.contract = Contract.invariant_;
        parent.debug_ = true;
        parent.ctfe = true;
        parent.traitsCompiles = true;
        parent.inTemplateConstraint = true;
        parent.noAccessCheck = true;
        parent.ignoresymbolvisibility = true;
        parent.inCfile = true;
        parent.ctfeBlock = true;
        parent.knownACompileTimeOnlyContext = true;
        parent.deferSemantic3InCompilerHook = true;
        // NOT persistent: reset by resetAllFlags and never re-applied
        parent.ctor = true;
        parent.fullinst = true;
        parent.scopesym = new ScopeDsymbol();
        parent.nofree = true;

        const s = parent.push();
        expect(s).not.toBe(parent);
        expect(s.enclosing).toBe(parent);
        expect(s.scopesym).toBe(null);
        expect(s.slabel).toBe(null);
        expect(s.lastdc).toBe(null);
        expect(s.nofree).toBe(false);

        expect(s.contract).toBe(Contract.invariant_);
        expect(s.debug_).toBe(true);
        expect(s.ctfe).toBe(true);
        expect(s.traitsCompiles).toBe(true);
        expect(s.inTemplateConstraint).toBe(true);
        expect(s.noAccessCheck).toBe(true);
        expect(s.ignoresymbolvisibility).toBe(true);
        expect(s.inCfile).toBe(true);
        expect(s.ctfeBlock).toBe(true);
        expect(s.knownACompileTimeOnlyContext).toBe(true);
        expect(s.deferSemantic3InCompilerHook).toBe(true);

        expect(s.ctor).toBe(false);
        expect(s.fullinst).toBe(false);
    });

    test("push(ss) is the same push plus the scopesym (arity-collapsed overload, 04 §1A)", () => {
        const parent = new Scope();
        const sym = new ScopeDsymbol();
        const s = parent.push(sym);
        expect(s.scopesym).toBe(sym);
        expect(s.enclosing).toBe(parent);
        expect(parent.push().scopesym).toBe(null);
    });

    test("pop() returns the enclosing scope and empties fieldinit; inner()/getScopesym() walk up", () => {
        const parent = new Scope();
        const sym = new ScopeDsymbol();
        parent.scopesym = sym;
        const child = parent.push();       // scopesym == null
        const grand = child.push();

        expect(grand.inner()).toBe(parent);      // dmd/dscope.d:375
        expect(grand.getScopesym()).toBe(sym);   // dmd/dscope.d:388
        expect(grand.pop()).toBe(child);         // dmd/dscope.d:302
        expect(child.pop()).toBe(parent);
        expect(parent.pop()).toBe(null);
        expect(parent.ctorflow.fieldinit).toEqual([]);
    });

    test("startCTFE/endCTFE bracket a ctfe sub-scope (dmd/dscope.d:332/364)", () => {
        const parent = new Scope();
        parent.inCfile = true;
        const sc = parent.startCTFE();
        expect(sc.ctfe).toBe(true);
        expect(sc.inCfile).toBe(true);   // copyFlagsFrom(&this) restores the whole word
        expect(sc.enclosing).toBe(parent);
        expect(sc.needsCodegen()).toBe(false); // dmd/dscope.d:522
        expect(sc.endCTFE()).toBe(parent);
    });
});

describe("Scope predicates", () => {
    test("speculative / compile-time-context predicates read the two words (dmd/dscope.d:512, :545)", () => {
        const sc = new Scope();
        expect(sc.isFromSpeculativeSemanticContext()).toBe(false);
        expect(sc.isKnownToHaveACompileTimeContext()).toBe(false);
        sc.intypeof = 1; // `ubyte` -> truthiness expands to `!== 0` (09 §9)
        expect(sc.isFromSpeculativeSemanticContext()).toBe(true);
        expect(sc.isKnownToHaveACompileTimeContext()).toBe(true);
        sc.intypeof = 0;
        sc.condition = true;
        expect(sc.isFromSpeculativeSemanticContext()).toBe(false); // `condition` is not in this one
        expect(sc.isKnownToHaveACompileTimeContext()).toBe(true);
    });

    test("hasEdition/useDIP1000/useDIP25 with no module (dmd/dscope.d:528/534/540)", () => {
        const sc = new Scope();
        expect(sc.hasEdition(Edition.v2024)).toBe(false); // `_module` is null -> the `&&` short-circuits
        expect(sc.useDIP1000()).toBe(FeatureState.disabled);
        sc.previews.dip1000 = true;
        expect(sc.useDIP1000()).toBe(FeatureState.enabled);
        expect(sc.useDIP25()).toBe(FeatureState.disabled);
        sc.previews.dip25 = true;
        expect(sc.useDIP25()).toBe(FeatureState.enabled);
    });

    test("setNoFree marks the whole chain (dmd/dscope.d:460); getEnclosingFunction with no func", () => {
        const a = new Scope();
        const b = a.push();
        const c = b.push();
        expect(c.nofree).toBe(false);
        c.setNoFree();
        expect(c.nofree).toBe(true);
        expect(b.nofree).toBe(true);
        expect(a.nofree).toBe(true);
        expect(c.getEnclosingFunction()).toBe(null); // dmd/dscope.d:438, `func` is null
    });
});
